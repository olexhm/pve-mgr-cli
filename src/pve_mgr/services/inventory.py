"""Build an Ansible inventory that reaches every guest through the right jump hosts."""

import shlex
from collections.abc import Sequence
from dataclasses import dataclass
from ipaddress import IPv4Address
from pathlib import Path

from pve_mgr.client import PveClient
from pve_mgr.errors import ConfigError, InventoryError
from pve_mgr.models import Config, Device
from pve_mgr.services.status import device_statuses

HEADER = "# Generated by pve-mgr inventory. Changes are overwritten on the next run.\n"


@dataclass(frozen=True)
class InventoryHost:
    device: Device
    address: IPv4Address
    proxy_jumps: tuple[str, ...]

    @property
    def line(self) -> str:
        device = self.device
        ssh_args = f"-o StrictHostKeyChecking=accept-new -J {','.join(self.proxy_jumps)}"
        return (
            f"{device.name} ansible_host={self.address} ansible_user={device.ansible_user} "
            f"ansible_port={device.ssh_port} ansible_ssh_common_args={shlex.quote(ssh_args)}"
        )


@dataclass(frozen=True)
class Inventory:
    hosts: tuple[InventoryHost, ...]
    skipped: tuple[tuple[str, str], ...]

    def render(self) -> str:
        return HEADER + "".join(f"{host.line}\n" for host in self.hosts)


def build_inventory(client: PveClient, devices: Sequence[Device], config: Config) -> Inventory:
    """One host per reachable guest.

    The jump chain is the Proxmox node the guest runs on, then either the
    device's own `proxy_jumps` or the declared gateway of its first bridge.
    """
    statuses = device_statuses(client, devices)
    skipped = [(s.device.name, "does not exist") for s in statuses if s.guest is None]
    located = [s for s in statuses if s.guest is not None]

    gateways: dict[str, tuple[Device, IPv4Address]] = {}
    for status in located:
        served = status.device.served_bridge
        if served is None:
            continue
        if status.address is None:
            raise InventoryError(
                f"Gateway {status.device.name} has no address yet, so guests on {served} "
                "cannot be reached. Start it and try again."
            )
        gateways[served] = (status.device, status.address)

    hosts: list[InventoryHost] = []
    for status in located:
        device, guest = status.device, status.guest
        assert guest is not None
        if status.address is None:
            skipped.append((device.name, f"no address ({guest.status})"))
            continue
        jumps = [_node_target(config, guest.node)]
        if device.proxy_jumps:
            jumps += device.proxy_jumps
        elif (gateway := gateways.get(device.bridge)) is not None:
            via, address = gateway
            port = "" if via.ssh_port == 22 else f":{via.ssh_port}"
            jumps.append(f"{via.ansible_user}@{address}{port}")
        hosts.append(InventoryHost(device, status.address, tuple(jumps)))

    return Inventory(tuple(hosts), tuple(skipped))


def write_inventory(path: Path, content: str) -> None:
    """Replace the file in one step, so a reader never sees half an inventory."""
    temporary = path.with_name(f".{path.name}.tmp")
    try:
        temporary.write_text(content, encoding="utf-8")
        temporary.replace(path)
    except OSError as exc:
        raise InventoryError(f"Cannot write {path}: {exc.strerror}") from exc


def _node_target(config: Config, node: str) -> str:
    target = config.nodes[node].ssh if node in config.nodes else None
    if target is None:
        raise ConfigError(
            f"nodes.{node}.ssh is not set in the config; the inventory needs it "
            "as the first SSH jump host"
        )
    return target
